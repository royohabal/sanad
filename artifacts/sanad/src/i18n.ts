const arabicToEnglish = Object.fromEntries(
  Object.entries(englishToArabic).map(([english, arabic]) => [arabic, english]),
);

let isArabic = false;
let observer: MutationObserver | undefined;

function translateText(text: string): string {
  const trimmed = text.trim();
  if (!trimmed) return text;
  const dictionary = isArabic ? englishToArabic : arabicToEnglish;
  let translated = dictionary[trimmed];
  if (!translated) {
    translated = Object.entries(dictionary)
      .sort(([left], [right]) => right.length - left.length)
      .reduce((value, [from, to]) => value.replaceAll(from, to), trimmed);
  }
  return translated ? text.replace(trimmed, translated) : text;
}

function translateSubtree(node: Node): void {
  if (node.nodeType === Node.TEXT_NODE) {
    const currentText = node.nodeValue;
    if (currentText) {
      const translated = translateText(currentText);
      if (translated !== currentText) node.nodeValue = translated;
    }
    return;
  }
  if (node instanceof HTMLElement) {
    for (const attribute of ["placeholder", "aria-label", "title"]) {
      const value = node.getAttribute(attribute);
      if (value) {
        const translated = translateText(value);
        if (translated !== value) node.setAttribute(attribute, translated);
      }
    }
  }
  node.childNodes.forEach(translateSubtree);
}

export function applyDocumentLanguage(arabic: boolean): void {
  isArabic = arabic;
  document.documentElement.dir = arabic ? "rtl" : "ltr";
  document.documentElement.lang = arabic ? "ar" : "en";
  translateSubtree(document.body);

  if (!observer) {
    observer = new MutationObserver((records) => {
      for (const record of records) {
        if (record.type === "attributes") translateSubtree(record.target);
        else if (record.type === "characterData") translateSubtree(record.target);
        else record.addedNodes.forEach(translateSubtree);
      }
    });
    observer.observe(document.body, {
      attributes: true,
      attributeFilter: ["placeholder", "aria-label", "title"],
      childList: true,
      characterData: true,
      subtree: true,
    });
  }
}
